const FIELDS=Object.freeze([
 {key:'spd',label:'Velocità'},
 {key:'atk',label:'Attacco'},
 {key:'spAtk',label:'Attacco Speciale'},
 {key:'def',label:'Difesa'},
 {key:'spDef',label:'Difesa Speciale'},
 {key:'maxHp',label:'PS massimi'}
]);
const effectiveValue=(fighter,key)=>{
 const fallback=key==='spAtk'?'atk':key==='spDef'?'def':key==='maxHp'?'hp':key;
 const value=fighter?.[key]??fighter?.[fallback];
 return Number.isFinite(Number(value))&&Number(value)>=0?Number(value):null;
};
// Usa i valori reali del roster Ultimon (compresi gli upgrade del Laboratorio),
// MA NON concede buff o svantaggi al solo apparire di due copie.
export function compareUltimonDuplicateStats(later,earlier){
 const rows=FIELDS.map(({key,label})=>{
  const mine=effectiveValue(later,key),other=effectiveValue(earlier,key);
  if(mine===null||other===null)return null;
  const delta=Number((mine-other).toFixed(2));
  return {key,label,mine,other,delta,relative:Math.abs(delta)/Math.max(mine,other,1)};
 }).filter(Boolean);
 if(!rows.length)return null;
 // Sceglie la differenza proporzionalmente più marcata; a parità preferisce
 // Velocità, Attacco e gli altri nell'ordine FIELDS.
 const leading=[...rows].sort((x,y)=>y.relative-x.relative)[0];
 return {...leading,kind:leading.delta>0?'advantage':leading.delta<0?'disadvantage':'tie',
  // I 6 valori servono alla visualizzazione: i valori non vengono modificati.
  rows:rows.map(({key,label,mine,other,delta})=>({key,label,mine,other,delta}))};
}
const tiePhrases=[
 'Abbiamo perfino le stesse statistiche. Il carattere, però, non si può copiare!',
 'I nostri numeri sono uguali. Saranno le scelte a renderci diversi.',
 'Stessa forza sulla carta... ma la scena non si divide così facilmente!',
 'Siamo pari nelle statistiche. Vediamo chi sorprende di più l’arena.'
];
// La prima parte è esclusiva per personaggio; la seconda valorizza il confronto
// dei dati. Nessuna frase aggiunta per un Multimon che non ha un doppione.
export function ultimonDuplicateReaction(character,earlier){
 const base=ULTIMON_DUPLICATE_REACTIONS[character?.id]||
  `Ehi, un altro ${character?.name||'me'}? A quanto pare siamo in due!`;
 const comparison=compareUltimonDuplicateStats(character,earlier);
 if(!comparison)return {line:base,comparison:null};
 const value=Math.abs(comparison.delta);
 let ending;
 if(comparison.kind==='advantage')
  ending=`Sul valore di ${comparison.label} sono avanti di ${value} punti!`;
 else if(comparison.kind==='disadvantage')
  ending=`Il mio doppione ha ${value} punti in più di ${comparison.label}. Questo sì che è interessante!`;
 else{
  let hash=0;
  for(const ch of String(character?.id||''))hash=(hash*31+ch.charCodeAt(0))>>>0;
  ending=tiePhrases[hash%tiePhrases.length];
 }
 return {line:base+' '+ending,comparison};
}
