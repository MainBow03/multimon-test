export function ultimonEntranceLine(character){
  if(!character)return '';
  const direct=ULTIMON_ENTRANCE_LINES[character.id];
  if(direct)return direct;
  // Compatibilità per personaggi aggiunti in futuro: preferisce una mossa
  // reale del Multimon invece di una battuta ripetuta per tutti.
  const move=(character.moves||[]).find(m=>m?.name&&m.power>0)?.name;
  return move
    ? `La mia ${move} farà ricordare a tutti il nome di ${character.name}!`
    : `Sono ${character.name}. Non sottovalutate la mia entrata in scena!`;
}
